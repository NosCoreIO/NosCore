using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace NosCore.DiGenerator;

[Generator]
public class MasterHubGenerator : IIncrementalGenerator
{
    public const string MasterHubAttribute = "NosCore.GameObject.InterChannelCommunication.MasterHubAttribute";
    private const string Communication = "global::NosCore.GameObject.InterChannelCommunication";

    private static readonly DiagnosticDescriptor MissingImplementation = new(
        "NOSHUB001",
        "Master hub has no implementation",
        "'{0}' is a master hub, so a class '{1}' implementing it must exist in the same namespace",
        "NosCore.Hubs",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor UnsupportedMethod = new(
        "NOSHUB002",
        "Master hub method must return a Task",
        "'{0}' must return Task or Task<T> to go through the master",
        "NosCore.Hubs",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DuplicateRequest = new(
        "NOSHUB003",
        "Master hub methods need distinct names",
        "'{0}' would send the same request as another method of the hub; give it a name of its own",
        "NosCore.Hubs",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var hubs = context.SyntaxProvider.ForAttributeWithMetadataName(
            MasterHubAttribute,
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.InterfaceDeclarationSyntax,
            static (ctx, _) => Describe((INamedTypeSymbol)ctx.TargetSymbol));

        context.RegisterSourceOutput(hubs, static (spc, hub) => Execute(hub, spc));
        context.RegisterSourceOutput(hubs.Collect(), static (spc, all) => ExecuteRegistrations(all, spc));
    }

    private static void ExecuteRegistrations(ImmutableArray<HubModel> hubs, SourceProductionContext context)
    {
        var implemented = hubs.Where(h => h.HasImplementation).OrderBy(h => h.HubName, System.StringComparer.Ordinal).ToList();
        if (implemented.Count == 0)
        {
            return;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by NosCore.DiGenerator. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace NosCore.GameObject.InterChannelCommunication");
        sb.AppendLine("{");
        sb.AppendLine("    public static class MasterHubs");
        sb.AppendLine("    {");
        sb.AppendLine("        // Wolverine only reads the service collection, and a factory lets it hand the hubs' own dependencies to the container.");
        sb.AppendLine("        public static void AddMasterHubs(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("        {");
        foreach (var hub in implemented)
        {
            var type = "global::" + hub.Namespace + "." + hub.HubName;
            sb.Append("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddTransient(services, ")
                .Append("static provider => global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<")
                .Append(type).AppendLine(">(provider));");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static void IncludeMasterHubReceivers(this global::Wolverine.WolverineOptions options)");
        sb.AppendLine("        {");
        foreach (var hub in implemented)
        {
            sb.Append("            options.Discovery.IncludeType(typeof(global::").Append(hub.Namespace).Append('.')
                .Append(hub.HubName).AppendLine("Receiver));");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        context.AddSource("MasterHubs.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    public static string ClientName(INamedTypeSymbol hubInterface) => HubName(hubInterface) + "Client";

    private static string HubName(INamedTypeSymbol hubInterface) => hubInterface.Name.Substring(1);

    private static HubModel Describe(INamedTypeSymbol hubInterface)
    {
        var hubName = HubName(hubInterface);
        var prefix = hubName.EndsWith("Hub", System.StringComparison.Ordinal)
            ? hubName.Substring(0, hubName.Length - 3)
            : hubName;
        var ns = hubInterface.ContainingNamespace.ToDisplayString();
        var implementation = hubInterface.ContainingNamespace.GetTypeMembers(hubName)
            .FirstOrDefault(t => t.AllInterfaces.Contains(hubInterface, SymbolEqualityComparer.Default));

        var diagnostics = new List<DiagnosticInfo>();
        if (implementation is null)
        {
            diagnostics.Add(new DiagnosticInfo(MissingImplementation, hubInterface.Locations.FirstOrDefault(),
                hubInterface.Name, hubName));
        }

        var methods = new List<MethodModel>();
        foreach (var method in hubInterface.GetMembers().OfType<IMethodSymbol>()
                     .Where(m => m.MethodKind == MethodKind.Ordinary))
        {
            if (method.ReturnType is not INamedTypeSymbol { Name: "Task" } returnType
                || returnType.ContainingNamespace.ToDisplayString() != "System.Threading.Tasks")
            {
                diagnostics.Add(new DiagnosticInfo(UnsupportedMethod, method.Locations.FirstOrDefault(),
                    method.Name, string.Empty));
                continue;
            }

            var operation = method.Name.EndsWith("Async", System.StringComparison.Ordinal)
                ? method.Name.Substring(0, method.Name.Length - 5)
                : method.Name;
            var request = (operation.Contains(prefix) ? operation : prefix + operation) + "Request";
            if (methods.Any(m => m.Request == request))
            {
                diagnostics.Add(new DiagnosticInfo(DuplicateRequest, method.Locations.FirstOrDefault(),
                    method.Name, string.Empty));
                continue;
            }

            var result = returnType.IsGenericType ? returnType.TypeArguments[0].ToDisplayString(TypeFormat) : null;
            var parameters = method.Parameters
                .Select(p => new ParameterModel(p.Type.ToDisplayString(TypeFormat), p.Name,
                    char.ToUpperInvariant(p.Name[0]) + p.Name.Substring(1)))
                .ToImmutableArray();
            methods.Add(new MethodModel(method.Name, request, result, new EquatableArray<ParameterModel>(parameters)));
        }

        return new HubModel(ns, hubInterface.Name, hubName, implementation is not null,
            new EquatableArray<MethodModel>(methods.ToImmutableArray()),
            new EquatableArray<DiagnosticInfo>(diagnostics.ToImmutableArray()));
    }

    private static void Execute(HubModel hub, SourceProductionContext context)
    {
        foreach (var diagnostic in hub.Diagnostics)
        {
            context.ReportDiagnostic(Diagnostic.Create(diagnostic.Descriptor, diagnostic.Location,
                diagnostic.First, diagnostic.Second));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by NosCore.DiGenerator. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.Append("namespace ").AppendLine(hub.Namespace);
        sb.AppendLine("{");

        foreach (var method in hub.Methods)
        {
            sb.Append("    public sealed record ").Append(method.Request).Append('(')
                .Append(string.Join(", ", method.Parameters.Select(p => p.Type + " " + p.Property)))
                .Append(") : ").Append(Communication).AppendLine(".IMasterRequest;");
            sb.AppendLine();
        }

        sb.Append("    public sealed class ").Append(hub.HubName).Append("Client(global::Wolverine.IMessageBus bus) : ")
            .AppendLine(hub.InterfaceName);
        sb.AppendLine("    {");
        foreach (var method in hub.Methods)
        {
            var call = method.Result is null
                ? $"{Communication}.MessageBusExtensions.SendToMasterAsync(bus, "
                : $"{Communication}.MessageBusExtensions.RequestAsync<{method.Result}>(bus, ";
            sb.Append("        public ").Append(TaskOf(method.Result)).Append(' ').Append(method.Name).Append('(')
                .Append(string.Join(", ", method.Parameters.Select(p => p.Type + " @" + p.Name))).AppendLine(") =>");
            sb.Append("            ").Append(call).Append("new ").Append(method.Request).Append('(')
                .Append(string.Join(", ", method.Parameters.Select(p => "@" + p.Name))).AppendLine("));");
            sb.AppendLine();
        }

        sb.AppendLine("    }");

        if (hub.HasImplementation)
        {
            sb.AppendLine();
            sb.Append("    public static class ").Append(hub.HubName).AppendLine("Receiver");
            sb.AppendLine("    {");
            foreach (var method in hub.Methods)
            {
                var arguments = string.Join(", ", method.Parameters.Select(p => "request." + p.Property));
                if (method.Result is null)
                {
                    sb.Append("        public static global::System.Threading.Tasks.Task Handle(").Append(method.Request)
                        .Append(" request, ").Append(hub.HubName).Append(" hub) => ((").Append(hub.InterfaceName).Append(")hub).").Append(method.Name).Append('(').Append(arguments).AppendLine(");");
                }
                else
                {
                    var reply = $"{Communication}.Reply<{method.Result}>";
                    sb.Append("        public static async global::System.Threading.Tasks.Task<").Append(reply).Append("> Handle(")
                        .Append(method.Request).Append(" request, ").Append(hub.HubName).Append(" hub) =>").AppendLine();
                    sb.Append("            new(await ((").Append(hub.InterfaceName).Append(")hub).").Append(method.Name).Append('(').Append(arguments).AppendLine("));");
                }

                sb.AppendLine();
            }

            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        context.AddSource(hub.Namespace + "." + hub.HubName + ".g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string TaskOf(string? result) => result is null
        ? "global::System.Threading.Tasks.Task"
        : $"global::System.Threading.Tasks.Task<{result}>";

    private sealed record HubModel(string Namespace, string InterfaceName, string HubName, bool HasImplementation,
        EquatableArray<MethodModel> Methods, EquatableArray<DiagnosticInfo> Diagnostics);

    private sealed record MethodModel(string Name, string Request, string? Result, EquatableArray<ParameterModel> Parameters);

    private sealed record ParameterModel(string Type, string Name, string Property);

    private sealed record DiagnosticInfo(DiagnosticDescriptor Descriptor, Location? Location, string First, string Second);

    private readonly struct EquatableArray<T>(ImmutableArray<T> items) : System.IEquatable<EquatableArray<T>>, IEnumerable<T>
    {
        private readonly ImmutableArray<T> _items = items;

        public bool Equals(EquatableArray<T> other) => _items.SequenceEqual(other._items);

        public override bool Equals(object? obj) => obj is EquatableArray<T> other && Equals(other);

        public override int GetHashCode() => _items.Aggregate(17, (h, i) => h * 31 + (i?.GetHashCode() ?? 0));

        public IEnumerator<T> GetEnumerator() => ((IEnumerable<T>)_items).GetEnumerator();

        System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();
    }
}
