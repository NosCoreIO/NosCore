            (MinigameType.MemoryTable, [999, 4999, 7999, 11999, 15999, 1000000]),
        ];

        public async Task InsertMinigamesAsync()
        {
            var rewards = Rewards
                .SelectMany(r => r.Items.Select(i => (r.MinigameVNum, r.Level, i.VNum, i.Amount)))
                .Select((r, index) => new MinigameRewardDto
                {
                    MinigameRewardId = (short)index,
                    MinigameVNum = r.MinigameVNum,
                    Level = r.Level,
                    ItemVNum = r.VNum,
                    Amount = r.Amount
                })
                .ToList();
            var scores = Scores
                .SelectMany(s => s.MaximumScores.Select((max, level) => new MinigameScoreDto
                {
                    MinigameScoreId = (short)((byte)s.Type * 10 + level),
                    MinigameType = s.Type,
                    Level = (byte)level,
                    MaximumScore = max
                }))
                .ToList();

            await minigameRewardDao.TryDeleteAsync(minigameRewardDao.LoadAll().Select(s => s.MinigameRewardId).ToList());
            await minigameRewardDao.TryInsertOrUpdateAsync(rewards);
            await minigameScoreDao.TryInsertOrUpdateAsync(scores);
        }
