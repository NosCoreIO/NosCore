        [
            (MinigameType.Quarry, [999, 4999, 7999, 11999, 15999, 1000000]),
            (MinigameType.Sawmill, [999, 4999, 9999, 13999, 17999, 1000000]),
            (MinigameType.FiringRange, [999, 3999, 7999, 14999, 24999, 1000000]),
            (MinigameType.Fishpond, [999, 3999, 7999, 11999, 19999, 1000000]),
